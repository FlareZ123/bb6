"""Partition generated Lean Audit proofs without changing any leaf witness.

Generated byMove lists have exactly 24 children in the existing move order.
Each chunk uses the original zipCheck; parent checks follow from the 24
child checks and a separately reduced first-hole query.
"""
import argparse
import re
from dataclasses import dataclass
from pathlib import Path
from itertools import product

@dataclass
class Node:
    head: str
    kids: list | None = None
    @property
    def size(self):
        return 1 if self.kids is None else 1 + sum(k.size for k in self.kids)
    def render(self):
        if self.kids is None:
            return self.head
        return self.head+'\n'+',\n'.join(k.render() for k in self.kids)+'\n])'

def parse(lines):
    line=next(lines).strip().removesuffix(',')
    if not line.startswith('.split '):
        assert line.startswith(('.cycle ','.last ','.far ','.proven ')),line
        return Node(line)
    assert re.fullmatch(r'\.split \d+ \([^)]*\) \(byMove \[',line),line
    children=[parse(lines) for _ in range(24)]
    assert next(lines).strip().removesuffix(',')=='])'
    return Node(line,children)

def move(i):
    return f'⟨{str(i>=12).lower()},{str(i%12>=6).lower()},{i%6}⟩'

def partition(text,limit=180):
    # Exactly one root Audit definition and its corresponding check theorem.
    pat=r'(?m)^def (\w+)( \(h : Exceptions\))? : Audit := ([\s\S]*?)\n(?:\n)?theorem (\w+)\2? : zipCheck (\d+) (.+?) \(?(\1)(?: h)?\)? = true := by (?:rfl|decide)\n'
    m=re.search(pat,text)
    if not m:
        raise ValueError('unexpected generated Kid module syntax')
    name,parameter,body,thm,bound,table,_=m.groups()
    parameter=parameter or ''
    arg=' h' if parameter else ''
    lines=iter(re.sub(r"(\]\))",r"\n\1",body.rstrip()).splitlines());tree=parse(lines)
    assert next(lines,None) is None
    if tree.size<=limit:return text,0
    code=[];counter=0
    def emit(node,p,nm=None,ck=None):
        nonlocal counter
        if nm is None:
            counter+=1;nm=f'{name}_part{counter}';ck=nm+'_checked'
        if node.size<=limit or node.kids is None:
            code.append(f'def {nm}{parameter} : Audit := {node.render()}\ntheorem {ck}{parameter} : zipCheck {bound} {p} ({nm}{arg}) = true := by rfl\n')
            return nm,ck
        n,s=re.fullmatch(r'\.split (\d+) (\([^)]*\)) \(byMove \[',node.head).groups()
        cs=[]
        for i,k in enumerate(node.kids):
            cs.append(emit(k,f'(refine {p} {s} (some {move(i)}))'))
        cstr=','.join(f'({cn}{arg})' for cn,_ in cs)
        code.append(f'def {nm}{parameter} : Audit := .split {n} {s} (byMove [{cstr}])\n')
        code.append(f'theorem {ck}{parameter} : zipCheck {bound} {p} ({nm}{arg}) = true := by\n')
        code.append(f'  change (zipQueryOK {bound} {p} {n} {s} && allMoves (fun mv => zipCheck {bound} (refine {p} {s} (some mv)) (byMove [{cstr}] mv))) = true\n')
        code.append('  simp only [Bool.and_eq_true]\n  refine ⟨by rfl, allMoves_of _ ?_⟩\n  intro mv\n  rcases mv with ⟨w,r,q⟩\n  have hq : q = 0 ∨ q = 1 ∨ q = 2 ∨ q = 3 ∨ q = 4 ∨ q = 5 := by omega\n  rcases hq with rfl|rfl|rfl|rfl|rfl|rfl\n  all_goals cases w <;> cases r\n')
        for q,w,r in product(range(6),range(2),range(2)):
            code.append(f'  · exact {cs[12*w+6*r+q][1]}{arg}\n')
        return nm,ck
    emit(tree,table,name,thm)
    return text[:m.start()]+'\n'.join(code)+text[m.end():],counter

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('directory',type=Path);ap.add_argument('prefix');ap.add_argument('--limit',type=int,default=180);args=ap.parse_args()
    paths=sorted(args.directory.glob(args.prefix+'Kid[0-9][0-9].lean'))
    assert len(paths)==24, (args.prefix,len(paths))
    for path in paths:
        text=path.read_text();out,n=partition(text,args.limit)
        if n:
            path.write_text(out);print(path.name,n,'subproofs',flush=True)
