// Deterministic generator for F289 fine checkpoint certificates.
function exactEngine(engineText,replayText){
 const match=replayText.match(/const replacements = ({[\s\S]*?});\nlet code/);if(!match)throw Error("replacement table");
 const replacements=new Function("return "+match[1])();
 for(const [oldText,newText] of Object.entries(replacements)){if(!engineText.includes(oldText))throw Error("missing replacement");engineText=engineText.split(oldText).join(newText)}
 const start=engineText.indexOf("const tokenRE"),end=engineText.indexOf("const machineMatch");if(start<0||end<start)throw Error("engine boundaries");
 return new Function(engineText.slice(start,end)+"\nreturn {parseState,runBatches,stable};")();
}

function leanState(s){
 const list=(xs,render)=>xs.length?"[\n    "+xs.map(render).join(",\n    ")+"\n  ]":"[]";
 const items=xs=>list(xs,x=>x.t==="z"?`.z ${x.c}`:x.t==="d"?`.d ${x.v}`:`.k ${x.r} ${x.c}`);
 const ls=s.ls.t==="raw"?`.raw ${items(s.ls.items)}`:`.clean ${s.ls.c0} ${list(s.ls.segs,([r,c])=>`(${r}, ${c})`)} ${s.ls.bot}`;
 return `⟨.${s.mode}, ${ls}, ${items(s.R)}, ${s.halted}⟩`;
}

function generateFineRoots(roots,engineText,replayText,counts){
 const {parseState,runBatches,stable}=exactEngine(engineText,replayText);
 const header=roots.slice(0,roots.indexOf("\nnamespace First\n")).split("\n-- Fine checkpoints: generated by generate_micro_checkpoints.js.")[0].trimEnd();
 const out=[header,"\n-- Fine checkpoints: generated by generate_micro_checkpoints.js.","-- Every new 20-batch edge and cost is checked by kernel rfl.","-- Original upstream checkpoint literals and total score are preserved.\n"];const stats=[];
 for(const [fi,family] of ["First","Second"].entries()){
 const section=roots.split("namespace "+family+"\n")[1].split("\nend "+family)[0];
 const original=new Map([...section.matchAll(/def (ckpt\d+) : RleFullState := ([\s\S]*?⟩)/g)].map(m=>[m[1],{literal:m[2],state:parseState(m[2])}]));
 const meta=counts.machines[fi],defs=new Map(),edges=[],coarse=[];const first=meta.chunkBounds[0].from;
 let state=original.get(first).state,current=first,batch=0,total=0n;defs.set(first,original.get(first).literal);
 for(const ch of meta.chunkBounds){
 if(current!==ch.from||stable(state)!==stable(original.get(ch.from).state))throw Error("coarse from "+ch.from);
 if(ch.batches%20)throw Error("uneven chunk");coarse.push(edges.length);let subtotal=0n;
 for(let offset=0;offset<ch.batches;offset+=20){
 const [next,cost]=runBatches(20,state);batch+=20;subtotal+=cost;total+=cost;
 const last=offset+20===ch.batches;let target=null;
 if(!last||ch.to!==null){target=last?ch.to:`micro_${batch}`;if(last&&stable(next)!==stable(original.get(target).state))throw Error("state "+target);defs.set(target,last?original.get(target).literal:leanState(next))}
 else if(!next.halted)throw Error("not halted");
 edges.push({from:current,to:target,cost});state=next;current=target;
 }
 if(subtotal!==BigInt(ch.bound))throw Error("cost "+ch.from);
 }
 if(total!==BigInt(meta.rleTransitionCostCandidate)||total+1n!==BigInt(meta.successfulPrimitiveStepCandidate)||total+2n!==BigInt(meta.includingHaltAttemptCandidate))throw Error("total");
 out.push(`namespace ${family}\n`);
 for(const [name,literal] of defs)out.push(`def ${name} : RleFullState := ${literal}\n`);
 for(const [i,e] of edges.entries()){
 const proposition=e.to?`runBatches 20 ${e.from} = ${e.to}`:`(runBatches 20 ${e.from}).halted = true`;
 out.push(`theorem micro_run_${i} : ${proposition} := rfl\ntheorem micro_cost_${i} : costBatches 20 ${e.from} = ${e.cost} := rfl\n`);
 }
 let rest=0n;const suffix=[];
 for(let i=edges.length-1;i>=0;i--){const e=edges[i],sum=e.cost+rest;suffix[i]=sum;
 const term=e.to===null?
 `counted_final_chunk (target_tm := ${family}.target_tm) (b := 20) (k := ${e.cost}) (s := ${e.from})\n    micro_run_${i} micro_cost_${i}`:
 `counted_chunk_back (target_tm := ${family}.target_tm) (b := 20) (k := ${e.cost}) (n := ${rest}) (s1 := ${e.from}) (s2 := ${e.to})\n    micro_run_${i} micro_cost_${i} micro_reach_${i+1}`;
 out.push(`theorem micro_reach_${i} : StateHaltsAt ${family}.target_tm ${e.from} ${sum} :=\n  ${term}\n`);rest=sum;
 }
 for(const [i,j] of coarse.entries())out.push(`theorem counted_reach_${i} : StateHaltsAt ${family}.target_tm ${edges[j].from} ${suffix[j]} := micro_reach_${j}\n`);
 const halt=section.slice(section.indexOf("theorem halts_exact"));out.push(halt.trimEnd(),`end ${family}\n`);
 stats.push({family,edges:edges.length,coarse:coarse.length,successful:String(total+1n),score:String(total+2n)});
 }
 out.push("end BB6.Agent17.RleCounted\n");return {source:out.join("\n"),stats};
}
