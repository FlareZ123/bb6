"""Emit a kernel-checkable, sharded Lean proof for Raw56 residual M42763.

The finite relation is generated by m42763_block_cert.py. This emitter only changes
proof granularity: each of 12 state/symbol tries is checked as eight low-bit subtries,
then reassembled by TwoSidedChunks.Trie.all_of_subtrees.
"""
from pathlib import Path
import argparse, sys

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parent))
from m42763_block_cert import TABLE, LEFT, RIGHT, EXPECTED, abstract, blockgram, emit

DEPTH = 4
CHUNKS = 1 << DEPTH
NS = "BB6.Agent4Raw56RootE11LB.M42763Block"
INNER = NS + ".M42763"

def certificate():
    raw = TABLE.replace("_", "")
    p = [raw[i:i+3] for i in range(0, 36, 3)]
    cert = abstract(p, blockgram(LEFT), blockgram(RIGHT))
    got = (cert[1], len(cert[-1][0]), len(cert[-1][1]))
    assert cert[0] and got == EXPECTED, (cert[0], got)
    return p, cert

def row_expr(q, a):
    b = "true" if a else "false"
    return f"""(row cert ({q} : Fin 6) {b}).all (fun i =>
      stateStepOK table cert ({q} : Fin 6) {b}
        (i / cert.right.edges.size) (i % cert.right.edges.size)) = true"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    args = ap.parse_args()
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    p, cert = certificate()
    body = emit("42763", p, cert)
    data_body = body[:body.index("theorem checked")]
    data = (
        "import TwoSidedAutomata\n"
        "set_option maxRecDepth 100000\n"
        "set_option maxHeartbeats 0\n"
        f"namespace {NS}\n"
        "open BB6Coverage\n"
        + data_body
        + "\nend M42763\n"
        + f"end {NS}\n"
    )
    (out / "M42763Data.lean").write_text(data)

    base = f"""import M42763Data
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace {INNER}
open BB6.Agent4Automata
theorem base : 0 < cert.left.edges.size ∧ 0 < cert.right.edges.size ∧
  (cert.left.pop 0).contains (false,0) = true ∧
  (cert.right.pop 0).contains (false,0) = true ∧
  stateOK cert 0 false 0 0 = true := by decide
#print axioms base
end {INNER}
"""
    (out / "M42763Base.lean").write_text(base)

    for q in range(6):
        for a, tag in ((False, "f"), (True, "t")):
            b = "true" if a else "false"
            for r in range(CHUNKS):
                chunk = f"""import M42763Data
import TwoSidedChunks
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace {INNER}
open BB6Coverage
open BB6.Agent4Automata
open BB6.Agent4Chunks
theorem chunk{q}{tag}_{r} :
    (subtree {DEPTH} {r} (row cert ({q} : Fin 6) {b})).all (fun i =>
      stateStepOK table cert ({q} : Fin 6) {b}
        (({CHUNKS}*i+{r}) / cert.right.edges.size)
        (({CHUNKS}*i+{r}) % cert.right.edges.size)) = true := by rfl
end {INNER}
"""
                (out / f"M42763Chunk{q}{tag}_{r}.lean").write_text(chunk)

            imports = "\n".join(f"import M42763Chunk{q}{tag}_{r}" for r in range(CHUNKS))
            disj = " ∨ ".join(f"r = {r}" for r in range(CHUNKS))
            rcases = " | ".join("rfl" for _ in range(CHUNKS))
            branches = "\n".join(f"  · simpa using chunk{q}{tag}_{r}" for r in range(CHUNKS))
            row = f"""{imports}
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace {INNER}
open BB6Coverage
open BB6.Agent4Automata
open BB6.Agent4Chunks
theorem row{q}{tag} :
    {row_expr(q, a)} := by
  apply BB6.Agent4Chunks.Trie.all_of_subtrees
    (row cert ({q} : Fin 6) {b})
    (fun i => stateStepOK table cert ({q} : Fin 6) {b}
      (i / cert.right.edges.size) (i % cert.right.edges.size)) {DEPTH}
  intro r hr
  have hrange : {disj} := by omega
  rcases hrange with {rcases}
{branches}
#print axioms row{q}{tag}
end {INNER}
"""
            (out / f"M42763Row{q}{tag}.lean").write_text(row)

    imports = "\n".join(
        f"import M42763Row{q}{tag}"
        for q in range(6) for tag in ("f", "t")
    )
    final = f"""{imports}
import M42763Base
set_option maxRecDepth 100000
set_option maxHeartbeats 0
namespace {INNER}
open BB6Coverage
open BB6.Agent4Automata
theorem checked : BB6.Agent4Automata.check table cert = true := by
  apply BB6.Agent4Chunks.check_of_rows12 base
  simp only [BB6.Agent4Chunks.rows12, BB6.Agent4Chunks.rowOK, Bool.and_eq_true]
  exact ⟨⟨row0f,row0t⟩,⟨⟨row1f,row1t⟩,⟨⟨row2f,row2t⟩,
    ⟨⟨row3f,row3t⟩,⟨⟨row4f,row4t⟩,⟨row5f,row5t⟩⟩⟩⟩⟩⟩
theorem never (m : Machine) (hm : compatible table m) : NeverHalts m :=
  BB6.Agent4Automata.never table cert checked m hm
#print axioms checked
#print axioms never
end {INNER}
"""
    (out / "M42763Final.lean").write_text(final)
    print(f"M42763 split proof: joint={EXPECTED[0]} rows=12 chunks={12*CHUNKS}")

if __name__ == "__main__":
    main()
