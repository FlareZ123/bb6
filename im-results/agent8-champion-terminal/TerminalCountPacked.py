SHA256 = "883cc5c982f10af69b10508a0bb141bf6f1b915ae4dbd3437e35be228caf81f3"

def main():
    source = zlib.decompress(base64.b64decode("".join(PACKED.split())))
    assert hashlib.sha256(source).hexdigest() == SHA256
    dest = Path(__file__).with_name("TerminalCount.lean")
    lock = dest.with_name(dest.name + ".lock")
    fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_RDWR, 0o600)
    try:
        with tempfile.NamedTemporaryFile(dir=dest.parent, delete=False) as tmp:
            tmp.write(source)
            temporary = Path(tmp.name)
        os.replace(temporary, dest)
    finally:
        os.close(fd)
        lock.unlink()
    print(f"Restored {dest} ({len(source)} bytes), SHA256 {SHA256}")

if __name__ == "__main__":
    main()
