"""Generate the exact q=37 two-feeder finite-shadow Lean certificate.

The graph search has no transition-depth cutoff. Lean independently checks
all edges up to the certified 2-adic cutoff K; the no-2^K-divisor invariant
then excludes every larger edge depth.
"""
from pathlib import Path
import os

from exact_fixed_shadow import fixed_shadow

Q = 37
EXPECTED = ((3927, 250, 9), (3823, 250, 9))


def lean_nodes(name: str, nodes: list[tuple[int, int]]) -> str:
    rows = [f"  ({m},{z})" for m, z in nodes]
    chunks = [", ".join(rows[i:i + 6]) for i in range(0, len(rows), 6)]
    return f"def {name} : List (Nat×Nat) := [\n" + ",\n".join(chunks) + "\n]\n"


def main() -> None:
    results = [fixed_shadow(Q, feeder) for feeder in (0, 1)]
    if any(result["status"] != "closed" for result in results):
        raise RuntimeError(f"q={Q} shadow graph is not closed: {results}")
    observed = tuple(
        (result["count"], result["max_cost"], result["max_v2_z"])
        for result in results
    )
    if observed != EXPECTED:
        raise RuntimeError(f"q={Q} census changed: {observed!r}")
    budget = max(result["max_cost"] for result in results)
    cutoff = max(result["max_v2_z"] for result in results) + 1
    if budget + cutoff + 3 > 15 * Q:
        raise RuntimeError("the source theorem's budget inequality fails")

    L0, L1 = 16 * Q + 8, 16 * Q + 9
    root0, root1 = 12 * Q + 4, 10 * Q + 4
    parts = [
        "import QBudgetFiniteK",
        "import UniformUniversalParamK",
        "set_option maxRecDepth 16384",
        "set_option maxHeartbeats 0",
        "namespace BB6.Agent9Q37",
        "open BB6.Agent9BudgetFiniteK",
        "",
        "/-- Exact complete shadow closures at q=37, independently generated by",
        "    unbounded integer BFS. The finite checker verifies every edge depth",
        "    below K=10; the 2^K nondivisibility certificate excludes all larger depths. -/",
        lean_nodes("nodes0", results[0]["nodes"]),
        f"theorem root0 : (0,{root0})∈nodes0 := by decide",
        f"theorem check0 : BB6.Agent9BudgetFiniteK.checkGraphK {cutoff} {L0} nodes0 = true := by decide",
        f"theorem boundCheck0 : nodes0.all (fun p => decide (p.1≤{budget} ∧ ¬2^{cutoff}∣p.2)) = true := by decide",
        f"theorem closed0 (m z t v zp : Nat) (hm : (m,z)∈nodes0)",
        f"    (hd:z=2^t*v) (hn:2*zp+1={L0}+m+t+v) :",
        "    (m+t+1,zp)∈nodes0 :=",
        f"  closed_of_checkK {cutoff} {budget} {L0} nodes0 check0 boundCheck0 m z t v zp hm hd hn",
        f"theorem small0 (m z : Nat) (hm : (m,z)∈nodes0) : m≤{budget} := by",
        "  have h := (List.all_eq_true.mp boundCheck0) (m,z) hm",
        "  exact (of_decide_eq_true h).1",
        f"theorem noCutoff0 (m z : Nat) (hm : (m,z)∈nodes0) : ¬2^{cutoff}∣z := by",
        "  have h := (List.all_eq_true.mp boundCheck0) (m,z) hm",
        "  exact (of_decide_eq_true h).2",
        lean_nodes("nodes1", results[1]["nodes"]),
        f"theorem root1 : (0,{root1})∈nodes1 := by decide",
        f"theorem check1 : BB6.Agent9BudgetFiniteK.checkGraphK {cutoff} {L1} nodes1 = true := by decide",
        f"theorem boundCheck1 : nodes1.all (fun p => decide (p.1≤{budget} ∧ ¬2^{cutoff}∣p.2)) = true := by decide",
        f"theorem closed1 (m z t v zp : Nat) (hm : (m,z)∈nodes1)",
        f"    (hd:z=2^t*v) (hn:2*zp+1={L1}+m+t+v) :",
        "    (m+t+1,zp)∈nodes1 :=",
        f"  closed_of_checkK {cutoff} {budget} {L1} nodes1 check1 boundCheck1 m z t v zp hm hd hn",
        f"theorem small1 (m z : Nat) (hm : (m,z)∈nodes1) : m≤{budget} := by",
        "  have h := (List.all_eq_true.mp boundCheck1) (m,z) hm",
        "  exact (of_decide_eq_true h).1",
        f"theorem noCutoff1 (m z : Nat) (hm : (m,z)∈nodes1) : ¬2^{cutoff}∣z := by",
        "  have h := (List.all_eq_true.mp boundCheck1) (m,z) hm",
        "  exact (of_decide_eq_true h).2",
        "theorem blank_no_critical_594_plus_2pow264 (r : Nat) :",
        "    ¬ BB6.Agent1.Reach 2",
        f"      (14*2^(16*(37+2^({cutoff}+{budget})*r)+2) -",
        f"       2*(16*(37+2^({cutoff}+{budget})*r)+2)-10) := by",
        "  exact BB6.Agent9UniformParamK.universal_blank_critical_cylinder_param_K",
        f"    {cutoff} {budget} {Q} (by decide) (by decide)",
        "    nodes0 nodes1 root0 root1",
        "    closed0 closed1 small0 small1 noCutoff0 noCutoff1 r",
        "#print axioms blank_no_critical_594_plus_2pow264",
        "end BB6.Agent9Q37",
        "",
    ]
    target = Path(__file__).with_name("Q37Budget.lean")
    lock = target.with_suffix(target.suffix + ".lock")
    fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        temporary = target.with_suffix(target.suffix + ".tmp")
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write("\n".join(parts))
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    finally:
        os.close(fd)
        lock.unlink()


if __name__ == "__main__":
    main()
