def atomic_write(path: Path, content: str) -> None:
    lock = path.with_suffix(path.suffix + ".lock")
    fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        tmp = path.with_suffix(path.suffix + ".tmp")
        with tmp.open("w", encoding="utf-8", newline="\n") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        os.close(fd)
        lock.unlink()


def proof(q: int, B: int, K: int, feeder: int) -> str:
    f = str(feeder)
    namespace = f"BB6.Agent9Q{q}Rows{f}"
    rows = f"rows{f}"
    S = f"S{f}"
    lines = [
        f"import Q{q}Rows{f}",
        "import QBudgetRows",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 0",
        f"namespace {namespace}",
        "open BB6.Agent9BudgetRows",
        "",
    ]
    for m in range(B + 1):
        lines.append(
            f"theorem row_{m} : checkRow {B} {K} {16*q+8+feeder} "
            f"{m} {rows} = true := by decide"
        )
    lines += [
        "",
        f"theorem row_all (m : Nat) (hm : m≤{B}) : "
        f"checkRow {B} {K} {16*q+8+feeder} m {rows} = true := by",
        "  match m with",
    ]
    for m in range(B + 1):
        lines.append(f"  | {m} => exact row_{m}")
    lines += [
        f"  | n+{B+1} => omega",
        "",
        f"def {S} (m z : Nat) : Prop := m≤{B} ∧ z∈{rows}[m]!",
        f"theorem root{f} : {S} 0 {(12 if feeder == 0 else 10)*q+4} := by",
        "  constructor",
        "  · omega",
        "  · decide",
        f"theorem small{f} (m z : Nat) (h : {S} m z) : m≤{B} := h.1",
        f"theorem noCutoff{f} (m z : Nat) (h : {S} m z) : ¬2^{K}∣z := by",
        "  have hcheck := row_all m h.1",
        f"  have hb := bounds_of_checkRow {B} {K} {16*q+8+feeder} "
        f"m {rows} hcheck z h.2",
        "  intro hd",
        f"  have he : 2^{K}≤z := Nat.le_of_dvd hb.1 hd",
        "  omega",
        f"theorem closed{f} (m z t v zp : Nat) (h : {S} m z)",
        f"    (hd : z=2^t*v) (hn : 2*zp+1={16*q+8+feeder}+m+t+v) : "
        f"{S} (m+t+1) zp := by",
        f"  rcases closed_of_checkRow {B} {K} {16*q+8+feeder} m "
        f"{rows} (row_all m h.1) z t v zp h.2 hd hn with ⟨hm,hmem⟩",
        "  exact ⟨hm,hmem⟩",
        f"#print axioms root{f}",
        f"#print axioms closed{f}",
        f"end {namespace}",
        "",
    ]
    return "\n".join(lines)


def budget_final(q: int, B: int, K: int) -> str:
    return "\n".join([
        f"import Q{q}Proof0",
        f"import Q{q}Proof1",
        "import UniformUniversalParamK",
        "set_option maxRecDepth 8192",
        "set_option maxHeartbeats 0",
        f"namespace BB6.Agent9Q{q}",
        "theorem no_critical_gateway (r : Nat) :",
        "    ¬ BB6.Agent1.Reach 2",
        f"      (14*2^(16*({q}+2^({K}+{B})*r)+2) -",
        f"       2*(16*({q}+2^({K}+{B})*r)+2)-10) := by",
        "  exact BB6.Agent9UniformParamK.universal_blank_critical_cylinder_param_K_of_predicates",
        f"    {K} {B} {q} (by decide) (by decide)",
        f"    BB6.Agent9Q{q}Rows0.S0 BB6.Agent9Q{q}Rows1.S1",
        f"    BB6.Agent9Q{q}Rows0.root0 BB6.Agent9Q{q}Rows1.root1",
        f"    BB6.Agent9Q{q}Rows0.closed0 BB6.Agent9Q{q}Rows1.closed1",
        f"    BB6.Agent9Q{q}Rows0.small0 BB6.Agent9Q{q}Rows1.small1",
        f"    BB6.Agent9Q{q}Rows0.noCutoff0 BB6.Agent9Q{q}Rows1.noCutoff1 r",
        "#print axioms no_critical_gateway",
        f"end BB6.Agent9Q{q}",
        "",
    ])


def run() -> None:
    selected = {int(value) for value in sys.argv[1:]}
    for q, B, K, expected in SPECS:
        if selected and q not in selected:
            continue
        records = [fixed_shadow(q, side) for side in (0, 1)]
        observed = tuple(
            (d["count"], d["max_cost"], d["max_v2_z"])
            for d in records if d["status"] == "closed"
        )
        if observed != expected:
            raise ValueError(f"q={q}: unexpected shadow graph {observed!r}")
        if B + K + 3 > 15 * q:
            raise ValueError(f"q={q}: source budget fails")
        for side, d in enumerate(records):
            rows = [[] for _ in range(B + 1)]
            for m, z in d["nodes"]:
                if m > B or z <= 0 or z >= 2**K:
                    raise ValueError(f"q={q}: outside invariant box {m,z}")
                rows[m].append(z)
            row_declarations = [
                f"private def cell_{m} : List Nat := [" + ", ".join(map(str, row)) + "]"
                for m, row in enumerate(rows)
            ]
            table = ", ".join(f"cell_{m}" for m in range(len(rows)))
            row_source = "\n".join([
                "import Lean",
                "set_option maxRecDepth 65536",
                "set_option maxHeartbeats 0",
                f"namespace BB6.Agent9Q{q}Rows{side}",
                *row_declarations,
                f"def rows{side} : Array (List Nat) := #[{table}]",
                f"end BB6.Agent9Q{q}Rows{side}",
                "",
            ])
            atomic_write(BASE / f"Q{q}Rows{side}.lean", row_source)
            atomic_write(BASE / f"Q{q}Proof{side}.lean", proof(q, B, K, side))
        atomic_write(BASE / f"Q{q}Budget.lean", budget_final(q, B, K))
        print(f"q={q} budget={B} cutoff=2^{K} nodes={expected}")


if __name__ == "__main__":
    run()
