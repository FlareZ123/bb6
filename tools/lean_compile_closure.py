#!/usr/bin/env python3
"""Compile the exact Lean import closure of one or more repository modules.

The repository stores Lean sources across many im-results directories and
some source modules are generated by tools/agent43_c32_certificate.py.
This helper resolves fully-qualified module paths and legacy flat-module
basenames, detects ambiguous sources, copies the closure into a flat Lean
workspace, and compiles topological layers in parallel. It is intentionally
strict: missing or ambiguous project imports are errors, not silently skipped
dependencies.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STANDARD_PREFIXES = ("Lean", "Init", "Std", "Batteries", "Mathlib")

# Add an explicit module -> repository-relative source path here only when
# two files with the same Lean module name are both present and the intended
# import target is known from the root module's source chain.
OVERRIDES: dict[str, str] = {}


def is_standard(module: str) -> bool:
    return any(module == p or module.startswith(p + ".") for p in STANDARD_PREFIXES)


def module_index(extra_roots: list[Path] | None = None) -> dict[str, list[Path]]:
    found: dict[str, list[Path]] = defaultdict(list)
    for search_root in [ROOT, *(extra_roots or [])]:
        if not search_root.is_dir():
            raise FileNotFoundError(f"Lean source root does not exist: {search_root}")
        for path in search_root.rglob("*.lean"):
            if any(part in {".git", ".lake", "build", "dist"} for part in path.parts):
                continue
            resolved = path.resolve()
            relative_module = path.relative_to(search_root).with_suffix("")
            qualified_name = ".".join(relative_module.parts)
            # Upstream imports use qualified names (e.g. Cryptids.Machines and
            # BusyBeaver.Bridge), while the shared im-results sources generally
            # import their flat module basenames. Index both spellings.
            for module_name in {qualified_name, resolved.stem}:
                if resolved not in found[module_name]:
                    found[module_name].append(resolved)
    return found


def display_source(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def resolve_source(module: str, index: dict[str, list[Path]]) -> Path:
    if module in OVERRIDES:
        path = ROOT / OVERRIDES[module]
        if not path.is_file():
            raise FileNotFoundError(f"override for {module} does not exist: {path}")
        return path
    candidates = index.get(module, [])
    if not candidates:
        raise FileNotFoundError(
            f"project import {module!r} has no .lean source in the indexed source roots"
        )
    if len(candidates) != 1:
        rendered = "\n  ".join(display_source(p) for p in candidates)
        raise RuntimeError(
            f"ambiguous module {module!r}; add an explicit OVERRIDES entry:\n  {rendered}"
        )
    return candidates[0]


def parse_imports(path: Path) -> list[str]:
    imports: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        # Lean supports qualified imports such as `public import` and
        # `meta import`; they participate in the same module dependency graph.
        match = re.match(r"^\s*(?:(?:public|meta)\s+)*import\s+(.+?)\s*$", line)
        if not match:
            continue
        for module in match.group(1).split():
            if not is_standard(module):
                imports.append(module)
    return imports


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_revision(root: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=root,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    return result.stdout.strip()


def tracked_source_paths(root: Path) -> set[str]:
    result = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=root,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    return {
        item.decode("utf-8")
        for item in result.stdout.split(b"\0")
        if item
    }


def source_kind(path: Path, tracked: set[str]) -> str:
    try:
        relative = path.relative_to(ROOT).as_posix()
    except ValueError:
        return "external"
    return "tracked" if relative in tracked else "generated-or-untracked"


def build_manifest(
    roots: list[Path],
    sources: dict[str, Path],
    graph: dict[str, list[str]],
    artifact_dir: Path,
    lean: str,
    label: str | None,
    provenance_inputs: list[Path],
    theorem: str | None,
    parent_table: str | None,
    weighted_bound: int | None,
    artifact_name: str | None,
    precompiled_metadata: dict | None = None,
) -> dict:
    if not artifact_dir.is_dir():
        raise FileNotFoundError(f"compiled artifact directory does not exist: {artifact_dir}")

    revision = git_revision(ROOT)
    tracked = tracked_source_paths(ROOT)
    version_result = subprocess.run(
        [lean, "--version"],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=True,
    )
    version = version_result.stdout.strip()
    if version_result.stderr.strip():
        print("[lean-closure] lean --version stderr: " +
              version_result.stderr.strip(), file=sys.stderr, flush=True)
    prefix_result = subprocess.run(
        [lean, "--print-prefix"], text=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True,
    )
    compiler_binary = Path(prefix_result.stdout.strip()) / "bin" / "lean"
    if not compiler_binary.is_file():
        raise FileNotFoundError(f"Lean compiler binary not found: {compiler_binary}")
    compiler_binary_sha256 = sha256_file(compiler_binary)

    modules = []
    for module in sorted(sources):
        source = sources[module]
        olean = artifact_dir / (module.replace(".", "/") + ".olean")
        if not olean.is_file():
            raise FileNotFoundError(
                f"compiled artifact for {module!r} is missing: {olean}"
            )
        modules.append({
            "module": module,
            "source_path": display_source(source),
            "source_kind": source_kind(source, tracked),
            "source_sha256": sha256_file(source),
            "project_imports": graph[module],
            "olean_path": module.replace(".", "/") + ".olean",
            "olean_sha256": sha256_file(olean),
        })

    module_map = {item["module"]: item for item in modules}
    identities: dict[str, str] = {}

    def module_identity(module: str) -> str:
        if module in identities:
            return identities[module]
        dependencies = []
        for dep in sorted(graph[module]):
            dep_identity = (
                f"standard:{version}:{dep}" if is_standard(dep)
                else module_identity(dep)
            )
            dependencies.append({"module": dep, "identity": dep_identity})
        import_hash = hashlib.sha256(
            json.dumps(dependencies, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        item = module_map[module]
        item["import_closure_sha256"] = import_hash
        payload = {
            "module": module,
            "source_sha256": item["source_sha256"],
            "project_imports": item["project_imports"],
            "olean_sha256": item["olean_sha256"],
            "import_closure_sha256": import_hash,
        }
        identity = hashlib.sha256(
            json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        item["module_identity_sha256"] = identity
        identities[module] = identity
        return identity

    for module in sorted(sources):
        module_identity(module)

    root_entries = []
    for root in roots:
        root_entries.append({
            "module": root.stem,
            "source_path": display_source(root),
            "source_sha256": sha256_file(root),
        })

    input_entries = []
    for path in sorted(provenance_inputs):
        if not path.is_file():
            raise FileNotFoundError(f"provenance input does not exist: {path}")
        input_entries.append({
            "path": display_source(path),
            "sha256": sha256_file(path),
        })

    return {
        "schema_version": 1,
        "label": label,
        "proof_source_revision": revision,
        "source_revisions": [revision],
        "workflow": {
            "name": os.environ.get("GITHUB_WORKFLOW"),
            "run_id": os.environ.get("GITHUB_RUN_ID"),
            "run_attempt": os.environ.get("GITHUB_RUN_ATTEMPT"),
            "workflow_head_sha": os.environ.get("GITHUB_SHA"),
        },
        "lean_version": version,
        "lean_binary": {
            "path": str(compiler_binary.resolve()),
            "sha256": compiler_binary_sha256,
        },
        "claim": {
            "theorem": theorem,
            "parent_table": parent_table,
            "weighted_bound": weighted_bound,
        },
        "artifact_name": artifact_name,
        "roots": root_entries,
        "module_count": len(modules),
        "modules": modules,
        "provenance_inputs": input_entries,
        "precompiled_core": precompiled_metadata,
    }


def compare_manifests(primary_path: Path, other_paths: list[Path]) -> None:
    primary = json.loads(primary_path.read_text(encoding="utf-8"))
    primary_modules = {item["module"]: item for item in primary["modules"]}
    primary_inputs = {item["path"]: item["sha256"] for item in primary["provenance_inputs"]}

    for other_path in other_paths:
        other = json.loads(other_path.read_text(encoding="utf-8"))
        other_modules = {item["module"]: item for item in other["modules"]}
        other_inputs = {item["path"]: item["sha256"] for item in other["provenance_inputs"]}
        common = sorted(primary_modules.keys() & other_modules.keys())
        mismatches: list[str] = []
        provenance_differences: list[str] = []

        revision_relation = (
            "same" if primary["proof_source_revision"] == other["proof_source_revision"]
            else "different (provenance only)"
        )

        if primary["lean_version"] != other["lean_version"]:
            mismatches.append(
                "Lean version differs: "
                f"{primary['lean_version']!r} != {other['lean_version']!r}"
            )
        if primary.get("lean_binary", {}).get("sha256") != other.get("lean_binary", {}).get("sha256"):
            mismatches.append("Lean compiler binary SHA-256 differs")

        for module in common:
            left = primary_modules[module]
            right = other_modules[module]
            for field in (
                "source_sha256", "project_imports", "olean_sha256",
                "import_closure_sha256", "module_identity_sha256",
            ):
                if field not in left or field not in right:
                    mismatches.append(f"{module}: missing identity field {field}")
                elif left[field] != right[field]:
                    mismatches.append(
                        f"{module}: {field} differs "
                        f"({left[field]!r} != {right[field]!r})"
                    )
            for dep in left["project_imports"]:
                if dep not in primary_modules or dep not in other_modules:
                    mismatches.append(
                        f"{module}: dependency {dep} is not present in both closures"
                    )

        for path in sorted(primary_inputs.keys() & other_inputs.keys()):
            if primary_inputs[path] != other_inputs[path]:
                provenance_differences.append(
                    f"{path}: SHA-256 differs "
                    f"({primary_inputs[path]} != {other_inputs[path]})"
                )

        print(
            "[lean-closure] manifest comparison "
            f"{primary.get('label') or primary_path.name} vs "
            f"{other.get('label') or other_path.name}: "
            f"{len(common)} shared module(s), "
            f"{len(mismatches)} identity mismatch(es), "
            f"{len(provenance_differences)} provenance difference(s); proof revisions "
            f"{primary['proof_source_revision']} / {other['proof_source_revision']} "
            f"({revision_relation})",
            flush=True,
        )
        for difference in provenance_differences:
            print(f"[lean-closure] provenance difference (non-gating): {difference}", file=sys.stderr)
        if mismatches:
            for mismatch in mismatches:
                print(f"[lean-closure] MANIFEST MISMATCH: {mismatch}", file=sys.stderr)
            raise RuntimeError(
                f"manifest compatibility failed against {other_path}"
            )


def compile_closure(
    roots: list[Path],
    workdir: Path,
    jobs: int,
    lean: str,
    extra_source_roots: list[Path] | None = None,
    manifest_path: Path | None = None,
    manifest_only: bool = False,
    artifact_dir: Path | None = None,
    label: str | None = None,
    provenance_inputs: list[Path] | None = None,
    compare_manifest_paths: list[Path] | None = None,
    theorem: str | None = None,
    parent_table: str | None = None,
    weighted_bound: int | None = None,
    artifact_name: str | None = None,
    precompiled_manifest_path: Path | None = None,
    precompiled_dir: Path | None = None,
    absolute_source_path: bool = False,
) -> None:
    index = module_index(extra_source_roots)
    sources: dict[str, Path] = {}
    graph: dict[str, list[str]] = {}
    visiting: list[str] = []
    visited: set[str] = set()
    topological: list[str] = []

    def visit(module: str, explicit: Path | None = None) -> None:
        if module in visited:
            return
        if module in visiting:
            cycle = " -> ".join(visiting + [module])
            raise RuntimeError(f"cyclic Lean import closure: {cycle}")
        source = explicit if explicit is not None else resolve_source(module, index)
        if not source.is_file():
            raise FileNotFoundError(source)
        sources[module] = source
        visiting.append(module)
        deps = parse_imports(source)
        graph[module] = deps
        for dep in deps:
            visit(dep)
        visiting.pop()
        visited.add(module)
        topological.append(module)

    for root in roots:
        visit(root.stem, root)

    precompiled: set[str] = set()
    precompiled_metadata: dict | None = None
    if precompiled_manifest_path is not None:
        if precompiled_dir is None:
            raise ValueError("--precompiled-manifest requires --precompiled-dir")
        if manifest_only:
            raise ValueError("--manifest-only cannot consume a precompiled manifest")
        if not precompiled_dir.is_dir():
            raise FileNotFoundError(f"precompiled artifact directory not found: {precompiled_dir}")
        base_manifest = json.loads(precompiled_manifest_path.read_text(encoding="utf-8"))
        if base_manifest.get("schema_version") != 1:
            raise ValueError("unsupported precompiled manifest schema")
        version_result = subprocess.run(
            [lean, "--version"], text=True,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True,
        )
        current_version = version_result.stdout.strip()
        if base_manifest.get("lean_version") != current_version:
            raise RuntimeError(
                "precompiled Lean version differs: "
                f"{base_manifest.get('lean_version')!r} != {current_version!r}"
            )
        prefix_result = subprocess.run(
            [lean, "--print-prefix"], text=True,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True,
        )
        current_compiler = Path(prefix_result.stdout.strip()) / "bin" / "lean"
        current_compiler_sha256 = sha256_file(current_compiler)
        if base_manifest.get("lean_binary", {}).get("sha256") != current_compiler_sha256:
            raise RuntimeError("precompiled Lean compiler binary SHA-256 differs")
        entries: dict[str, dict] = {}
        precompiled_identities: dict[str, str] = {}
        for entry in base_manifest.get("modules", []):
            module = entry.get("module")
            if not module or module in entries:
                raise ValueError(f"invalid or duplicate precompiled module entry: {module!r}")
            entries[module] = entry
        workdir.mkdir(parents=True, exist_ok=True)
        for module in topological:
            entry = entries.get(module)
            if entry is None:
                continue
            if entry.get("source_sha256") != sha256_file(sources[module]):
                continue
            if entry.get("project_imports") != graph[module]:
                continue
            relative = Path(entry.get("olean_path", ""))
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"unsafe precompiled object path for {module}: {relative}")
            source_olean = precompiled_dir / relative
            if not source_olean.is_file():
                continue
            if sha256_file(source_olean) != entry.get("olean_sha256"):
                continue
            if not all(dep in precompiled or is_standard(dep) for dep in graph[module]):
                continue
            dependencies = []
            for dep in sorted(graph[module]):
                dep_identity = (
                    f"standard:{current_version}:{dep}" if is_standard(dep)
                    else precompiled_identities[dep]
                )
                dependencies.append({"module": dep, "identity": dep_identity})
            expected_import_hash = hashlib.sha256(
                json.dumps(dependencies, sort_keys=True, separators=(",", ":")).encode()
            ).hexdigest()
            if entry.get("import_closure_sha256") != expected_import_hash:
                continue
            identity_payload = {
                "module": module,
                "source_sha256": entry["source_sha256"],
                "project_imports": entry["project_imports"],
                "olean_sha256": entry["olean_sha256"],
                "import_closure_sha256": expected_import_hash,
            }
            expected_identity = hashlib.sha256(
                json.dumps(identity_payload, sort_keys=True, separators=(",", ":")).encode()
            ).hexdigest()
            if entry.get("module_identity_sha256") != expected_identity:
                continue
            target_olean = workdir / relative
            target_olean.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_olean, target_olean)
            if sha256_file(target_olean) != entry["olean_sha256"]:
                raise RuntimeError(f"precompiled object copy hash mismatch: {module}")
            precompiled.add(module)
            precompiled_identities[module] = expected_identity
        precompiled_metadata = {
            "proof_source_revision": base_manifest.get("proof_source_revision"),
            "source_revisions": base_manifest.get(
                "source_revisions", [base_manifest.get("proof_source_revision")]
            ),
            "lean_binary_sha256": current_compiler_sha256,
            "manifest_sha256": sha256_file(precompiled_manifest_path),
            "reused_module_count": len(precompiled),
            "reused_modules": sorted(precompiled),
        }
        print(
            f"[lean-closure] reused {len(precompiled)} dependency-closed module(s) "
            f"from source revisions {precompiled_metadata['source_revisions']}",
            flush=True,
        )
    elif precompiled_dir is not None:
        raise ValueError("--precompiled-dir requires --precompiled-manifest")

    compiled_dir = artifact_dir or workdir
    if not manifest_only:
        workdir.mkdir(parents=True, exist_ok=True)
        for module, source in sources.items():
            target = workdir / (module.replace(".", "/") + ".lean")
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)

        env = os.environ.copy()
        env["LEAN_PATH"] = str(workdir)
        remaining = set(sources) - precompiled
        compiled: set[str] = set(precompiled)
        level_no = 0

        def compile_one(module: str) -> tuple[str, int]:
            target = workdir / (module.replace(".", "/") + ".lean")
            olean = workdir / (module.replace(".", "/") + ".olean")
            print(
                f"[lean-closure] compiling {module} <- {display_source(sources[module])}",
                flush=True,
            )
            result = subprocess.run(
                # Lean serializes source paths into some .olean metadata.
                # Relative source names are stable across independent workdirs.
                [lean, "-o", str(olean),
                 str(target if absolute_source_path else target.relative_to(workdir))],
                cwd=workdir,
                env=env,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
            )
            if result.stdout:
                print(result.stdout, end="", flush=True)
            if result.returncode != 0:
                raise subprocess.CalledProcessError(result.returncode, result.args)
            return module, result.returncode

        while remaining:
            ready = sorted(
                module for module in remaining
                if all(dep in compiled or is_standard(dep) for dep in graph[module])
            )
            if not ready:
                blocked = {
                    module: [
                        dep for dep in graph[module]
                        if dep not in compiled and not is_standard(dep)
                    ]
                    for module in sorted(remaining)
                }
                raise RuntimeError(f"no compilable import layer remains: {blocked}")
            level_no += 1
            print(
                f"[lean-closure] level {level_no}: {len(ready)} module(s)",
                flush=True,
            )
            with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
                futures = [pool.submit(compile_one, module) for module in ready]
                for future in concurrent.futures.as_completed(futures):
                    future.result()
            compiled.update(ready)
            remaining.difference_update(ready)

        print(
            f"[lean-closure] SUCCESS: compiled {len(compiled)} project modules "
            f"from {len(roots)} root(s) into {workdir}",
            flush=True,
        )
    else:
        print(
            f"[lean-closure] resolved {len(sources)} project modules "
            f"from {len(roots)} root(s); compiler execution skipped",
            flush=True,
        )

    if manifest_path is not None:
        manifest = build_manifest(
            roots,
            sources,
            graph,
            compiled_dir,
            lean,
            label,
            provenance_inputs or [],
            theorem,
            parent_table,
            weighted_bound,
            artifact_name,
            precompiled_metadata,
        )
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        print(
            f"[lean-closure] wrote manifest for {len(sources)} modules "
            f"to {manifest_path}",
            flush=True,
        )
        if compare_manifest_paths:
            compare_manifests(manifest_path, compare_manifest_paths)
    elif manifest_only:
        raise ValueError("--manifest-only requires --manifest")

def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("roots", nargs="+", help="root .lean source paths")
    parser.add_argument("--workdir", default="/tmp/lean-closure")
    parser.add_argument("--absolute-source-path", action="store_true",
                        help="use legacy absolute source arguments when reproducing old object identities")
    parser.add_argument("--source-root", action="append", default=[], metavar="DIR",
                        help="additional directory containing reconstructed Lean source files")
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--lean", default="lean")
    parser.add_argument("--manifest", help="write a JSON source/import/olean hash manifest")
    parser.add_argument(
        "--manifest-only",
        action="store_true",
        help="resolve source closure and hash precompiled oleans without compiling",
    )
    parser.add_argument(
        "--artifact-dir",
        help="directory containing precompiled oleans (defaults to --workdir)",
    )
    parser.add_argument("--label", help="human-readable name for this proof closure")
    parser.add_argument("--theorem", help="exact exported theorem established by this closure")
    parser.add_argument("--parent-table", help="literal partial transition table certified by the theorem")
    parser.add_argument("--weighted-bound", type=int, help="weighted first-one bound certified for the parent")
    parser.add_argument("--artifact-name", help="expected GitHub Actions artifact name")
    parser.add_argument(
        "--precompiled-manifest",
        help="manifest describing dependency-closed compiled modules available for reuse",
    )
    parser.add_argument(
        "--precompiled-dir",
        help="artifact directory containing the objects named by --precompiled-manifest",
    )
    parser.add_argument(
        "--provenance-input",
        action="append",
        default=[],
        metavar="PATH",
        help="hash a generator, specification, or other non-Lean input; repeatable",
    )
    parser.add_argument(
        "--compare-manifest",
        action="append",
        default=[],
        metavar="PATH",
        help="require shared modules and provenance inputs to have identical hashes",
    )
    parser.add_argument(
        "--override",
        action="append",
        default=[],
        metavar="MODULE=PATH",
        help="resolve an ambiguous project module to a repository-relative source path",
    )
    args = parser.parse_args()
    if args.manifest_only and not args.manifest:
        parser.error("--manifest-only requires --manifest")
    if args.compare_manifest and not args.manifest:
        parser.error("--compare-manifest requires --manifest")
    if args.manifest_only and not args.artifact_dir:
        parser.error("--manifest-only requires --artifact-dir")
    if bool(args.precompiled_manifest) != bool(args.precompiled_dir):
        parser.error("--precompiled-manifest and --precompiled-dir must be supplied together")
    if args.manifest_only and args.precompiled_manifest:
        parser.error("--manifest-only cannot consume a precompiled manifest")
    for entry in args.override:
        if "=" not in entry:
            parser.error(f"invalid --override {entry!r}; expected MODULE=PATH")
        module, source_path = entry.split("=", 1)
        if not module or not source_path:
            parser.error(f"invalid --override {entry!r}; expected MODULE=PATH")
        OVERRIDES[module] = source_path
    roots = [
        (ROOT / p).resolve() if not Path(p).is_absolute() else Path(p).resolve()
        for p in args.roots
    ]
    for root in roots:
        if not root.is_file():
            parser.error(f"root source does not exist: {root}")
    try:
        extra_roots = [Path(p).resolve() for p in args.source_root]
        provenance_inputs = [
            (ROOT / p).resolve() if not Path(p).is_absolute() else Path(p).resolve()
            for p in args.provenance_input
        ]
        compare_paths = [Path(p).resolve() for p in args.compare_manifest]
        compile_closure(
            roots,
            Path(args.workdir).resolve(),
            max(1, args.jobs),
            args.lean,
            extra_roots,
            Path(args.manifest).resolve() if args.manifest else None,
            args.manifest_only,
            Path(args.artifact_dir).resolve() if args.artifact_dir else None,
            args.label,
            provenance_inputs,
            compare_paths,
            args.theorem,
            args.parent_table,
            args.weighted_bound,
            args.artifact_name,
            Path(args.precompiled_manifest).resolve() if args.precompiled_manifest else None,
            Path(args.precompiled_dir).resolve() if args.precompiled_dir else None,
            args.absolute_source_path,
        )
    except Exception as exc:
        print(f"[lean-closure] ERROR: {exc}", file=sys.stderr, flush=True)
        return 1
    return 0


