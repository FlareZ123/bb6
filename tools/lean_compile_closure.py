#!/usr/bin/env python3
"""Compile the exact Lean import closure of one or more repository modules.

The repository stores Lean sources across many im-results directories and
some source modules are generated by tools/agent43_c32_certificate.py.
This helper resolves imports by module basename, detects ambiguous sources,
copies the closure into a flat Lean workspace, and compiles topological layers
in parallel. It is intentionally strict: missing or ambiguous project imports
are errors, not silently skipped dependencies.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STANDARD_PREFIXES = ("Lean", "Init", "Std", "Batteries", "Mathlib")

# Add an explicit module -> repository-relative source path here only when
# two files with the same Lean module name are both present and the intended
# import target is known from the root module's source chain.
OVERRIDES: dict[str, str] = {}


def is_standard(module: str) -> bool:
    return any(module == p or module.startswith(p + ".") for p in STANDARD_PREFIXES)


def module_index(extra_roots: list[Path] | None = None) -> dict[str, list[Path]]:
    found: dict[str, list[Path]] = defaultdict(list)
    for search_root in [ROOT, *(extra_roots or [])]:
        if not search_root.is_dir():
            raise FileNotFoundError(f"Lean source root does not exist: {search_root}")
        for path in search_root.rglob("*.lean"):
            if any(part in {".git", ".lake", "build", "dist"} for part in path.parts):
                continue
            found[path.stem].append(path)
    return found


def display_source(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def resolve_source(module: str, index: dict[str, list[Path]]) -> Path:
    if module in OVERRIDES:
        path = ROOT / OVERRIDES[module]
        if not path.is_file():
            raise FileNotFoundError(f"override for {module} does not exist: {path}")
        return path
    candidates = index.get(module, [])
    if not candidates:
        raise FileNotFoundError(
            f"project import {module!r} has no .lean source in the repository"
        )
    if len(candidates) != 1:
        rendered = "\n  ".join(display_source(p) for p in candidates)
        raise RuntimeError(
            f"ambiguous module {module!r}; add an explicit OVERRIDES entry:\n  {rendered}"
        )
    return candidates[0]


def parse_imports(path: Path) -> list[str]:
    imports: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^\s*import\s+(.+?)\s*$", line)
        if not match:
            continue
        for module in match.group(1).split():
            if not is_standard(module):
                imports.append(module)
    return imports


def compile_closure(
    roots: list[Path],
    workdir: Path,
    jobs: int,
    lean: str,
    extra_source_roots: list[Path] | None = None,
) -> None:
    index = module_index(extra_source_roots)
    sources: dict[str, Path] = {}
    graph: dict[str, list[str]] = {}
    visiting: list[str] = []
    visited: set[str] = set()

    def visit(module: str, explicit: Path | None = None) -> None:
        if module in visited:
            return
        if module in visiting:
            cycle = " -> ".join(visiting + [module])
            raise RuntimeError(f"cyclic Lean import closure: {cycle}")
        source = explicit if explicit is not None else resolve_source(module, index)
        if not source.is_file():
            raise FileNotFoundError(source)
        sources[module] = source
        visiting.append(module)
        deps = parse_imports(source)
        graph[module] = deps
        for dep in deps:
            visit(dep)
        visiting.pop()
        visited.add(module)

    for root in roots:
        visit(root.stem, root)

    workdir.mkdir(parents=True, exist_ok=True)
    for module, source in sources.items():
        target = workdir / (module.replace(".", "/") + ".lean")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)

    env = os.environ.copy()
    env["LEAN_PATH"] = str(workdir)
    remaining = set(sources)
    compiled: set[str] = set()
    level_no = 0

    def compile_one(module: str) -> tuple[str, int]:
        target = workdir / (module.replace(".", "/") + ".lean")
        olean = workdir / (module.replace(".", "/") + ".olean")
        print(f"[lean-closure] compiling {module} <- {display_source(sources[module])}", flush=True)
        result = subprocess.run(
            [lean, "-o", str(olean), str(target)],
            cwd=workdir,
            env=env,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        if result.stdout:
            print(result.stdout, end="", flush=True)
        if result.returncode != 0:
            raise subprocess.CalledProcessError(result.returncode, result.args)
        return module, result.returncode

    while remaining:
        ready = sorted(
            module for module in remaining
            if all(dep in compiled or is_standard(dep) for dep in graph[module])
        )
        if not ready:
            blocked = {
                module: [dep for dep in graph[module] if dep not in compiled and not is_standard(dep)]
                for module in sorted(remaining)
            }
            raise RuntimeError(f"no compilable import layer remains: {blocked}")
        level_no += 1
        print(f"[lean-closure] level {level_no}: {len(ready)} module(s)", flush=True)
        with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as pool:
            futures = [pool.submit(compile_one, module) for module in ready]
            for future in concurrent.futures.as_completed(futures):
                future.result()
        compiled.update(ready)
        remaining.difference_update(ready)

    print(
        f"[lean-closure] SUCCESS: compiled {len(compiled)} project modules "
        f"from {len(roots)} root(s) into {workdir}",
        flush=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("roots", nargs="+", help="root .lean source paths")
    parser.add_argument("--workdir", default="/tmp/lean-closure")
    parser.add_argument("--source-root", action="append", default=[], metavar="DIR",
                        help="additional directory containing reconstructed Lean source files")
    parser.add_argument("--jobs", type=int, default=8)
    parser.add_argument("--lean", default="lean")
    parser.add_argument(
        "--override",
        action="append",
        default=[],
        metavar="MODULE=PATH",
        help="resolve an ambiguous project module to a repository-relative source path",
    )
    args = parser.parse_args()
    for entry in args.override:
        if "=" not in entry:
            parser.error(f"invalid --override {entry!r}; expected MODULE=PATH")
        module, source_path = entry.split("=", 1)
        if not module or not source_path:
            parser.error(f"invalid --override {entry!r}; expected MODULE=PATH")
        OVERRIDES[module] = source_path
    roots = [(ROOT / p).resolve() for p in args.roots]
    for root in roots:
        if not root.is_file():
            parser.error(f"root source does not exist: {root}")
    try:
        extra_roots = [Path(p).resolve() for p in args.source_root]
        compile_closure(
            roots,
            Path(args.workdir).resolve(),
            max(1, args.jobs),
            args.lean,
            extra_roots,
        )
    except Exception as exc:
        print(f"[lean-closure] ERROR: {exc}", file=sys.stderr, flush=True)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
